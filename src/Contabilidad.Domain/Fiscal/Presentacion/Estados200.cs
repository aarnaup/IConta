    /// <summary>Casillas de las páginas 3 a 8 («B:nnnnn») con los saldos de las cuentas (debe − haber) al cierre.</summary>
    /// <param name="sinClasificar">Cuentas con saldo que no van a ninguna casilla (deberían ser ninguna).</param>
    public static IReadOnlyDictionary<string, object?> Casillas(IReadOnlyList<SaldoBalance> saldos, out IReadOnlyList<SaldoBalance> sinClasificar)
    {
        var balance = GeneradorEstados.Calcular(Balance, saldos);
        var pyg = GeneradorEstados.Calcular(PerdidasGanancias, saldos);
        sinClasificar = balance.SinClasificar.Concat(pyg.SinClasificar).ToList();
        var r = new Dictionary<string, object?>(StringComparer.Ordinal);
        foreach (var p in balance.Partidas.Concat(pyg.Partidas)) r["B:" + p.Id] = p.Importe;
        return r;
    }
